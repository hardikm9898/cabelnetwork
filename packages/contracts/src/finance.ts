import { fromPaise, toPaise } from '@cablenet/domain';
import { z } from 'zod';
import { businessDate, optionalTrimmed, paginationQuery, reason, trimmed, uuid } from './common';

/**
 * Money on the wire is a decimal string ("1500.00"). Integers are accepted for convenience.
 * The value is normalised to exactly two decimals; floats such as 0.1 are rejected.
 */
const money = z.union([z.string(), z.number().int()]).transform((v, ctx) => {
  try {
    return fromPaise(toPaise(v));
  } catch {
    ctx.addIssue({ code: 'custom', message: 'Enter an amount with at most 2 decimals, e.g. "1500" or "1500.50"' });
    return z.NEVER;
  }
});
export const positiveMoney = money.refine((v) => toPaise(v) > 0n, 'Amount must be greater than zero');
export const nonNegativeMoney = money.refine((v) => toPaise(v) >= 0n, 'Amount cannot be negative');
export const signedMoney = money.refine((v) => toPaise(v) !== 0n, 'Amount cannot be zero');

export const BILLING_MODES = ['AUTO', 'MANUAL'] as const;
export const BILLING_TIMINGS = ['ADVANCE', 'ARREARS'] as const;
export const PAYMENT_MODES = ['CASH', 'UPI', 'BANK_TRANSFER', 'CHEQUE', 'OTHER'] as const;
export type PaymentMode = (typeof PAYMENT_MODES)[number];
export const PAYMENT_STATUSES = ['PENDING_VERIFICATION', 'CONFIRMED', 'FAILED', 'REVERSED'] as const;
export const INVOICE_FILTER_STATUSES = ['UNPAID', 'PARTIALLY_PAID', 'PAID', 'CANCELLED', 'OVERDUE', 'OPEN'] as const;

// ---------------------------------------------------------------------------
// Subscriptions & billing
// ---------------------------------------------------------------------------

export const createSubscriptionRequest = z.object({
  monthlyRate: nonNegativeMoney,
  startDate: businessDate,
  billingIntervalMonths: z.number().int().min(1).max(24).default(1),
  /** Day of month periods start on (1–28). Defaults to the start date's day. */
  billingAnchorDay: z.number().int().min(1).max(28).optional(),
  billingTiming: z.enum(BILLING_TIMINGS).default('ADVANCE'),
  billingMode: z.enum(BILLING_MODES).default('AUTO'),
  dueDays: z.number().int().min(0).max(90).optional(),
  notes: optionalTrimmed(1000),
});
export type CreateSubscriptionRequest = z.infer<typeof createSubscriptionRequest>;

export const changeRateRequest = z.object({ monthlyRate: nonNegativeMoney, effectiveFrom: businessDate, reason });
export type ChangeRateRequest = z.infer<typeof changeRateRequest>;

/**
 * The customer's monthly charge from the next bill on (bills already made stay). A customer
 * without a plan starts billing on the 1st of next month at this charge.
 */
export const setMonthlyChargeRequest = z.object({ monthlyRate: nonNegativeMoney, reason: optionalTrimmed(300) });
export type SetMonthlyChargeRequest = z.infer<typeof setMonthlyChargeRequest>;

export const updateSubscriptionTermsRequest = z
  .object({
    billingIntervalMonths: z.number().int().min(1).max(24),
    billingAnchorDay: z.number().int().min(1).max(28),
    billingTiming: z.enum(BILLING_TIMINGS),
    billingMode: z.enum(BILLING_MODES),
    dueDays: z.number().int().min(0).max(90),
    notes: optionalTrimmed(1000),
  })
  .partial()
  .extend({ reason });
export type UpdateSubscriptionTermsRequest = z.infer<typeof updateSubscriptionTermsRequest>;

export const suspendRequest = z
  .object({ fromDate: businessDate, toDate: businessDate.nullish(), reason })
  .refine((v) => !v.toDate || v.toDate >= v.fromDate, { message: 'End date is before start date', path: ['toDate'] });
export type SuspendRequest = z.infer<typeof suspendRequest>;

export const reactivateRequest = z.object({ date: businessDate.optional(), reason });
export type ReactivateRequest = z.infer<typeof reactivateRequest>;

export const endSubscriptionRequest = z.object({ endDate: businessDate, reason });
export type EndSubscriptionRequest = z.infer<typeof endSubscriptionRequest>;

export const billingRunRequest = z.object({ asOf: businessDate.optional() });

export const manualInvoiceRequest = z.object({
  periodStart: businessDate,
  months: z.number().int().min(1).max(24),
  description: optionalTrimmed(300),
});
export type ManualInvoiceRequest = z.infer<typeof manualInvoiceRequest>;

export const listInvoicesQuery = paginationQuery.extend({
  customerId: uuid.optional(),
  status: z.enum(INVOICE_FILTER_STATUSES).optional(),
  from: businessDate.optional(),
  to: businessDate.optional(),
});
export type ListInvoicesQuery = z.infer<typeof listInvoicesQuery>;

// ---------------------------------------------------------------------------
// Payments
// ---------------------------------------------------------------------------

export const recordPaymentRequest = z
  .object({
    /** Generated by the client once per payment; retries with the same id never post twice. */
    clientTxnId: uuid,
    customerId: uuid,
    amount: positiveMoney,
    paymentDate: businessDate,
    mode: z.enum(PAYMENT_MODES),
    reference: z.string().trim().max(100).nullish(),
    notes: optionalTrimmed(1000),
    receivedAt: z.iso.datetime({ offset: true }).optional(),
    recordedOffline: z.boolean().default(false),
  })
  .refine((v) => !['UPI', 'BANK_TRANSFER', 'CHEQUE'].includes(v.mode) || !!v.reference, {
    message: 'A transaction reference (UTR / cheque number) is required for this payment mode',
    path: ['reference'],
  });
export type RecordPaymentRequest = z.infer<typeof recordPaymentRequest>;

export const verifyPaymentRequest = z.object({ note: optionalTrimmed(500) });
export const failPaymentRequest = z.object({ reason });
export const reversePaymentRequest = z.object({ reason });

export const listPaymentsQuery = paginationQuery.extend({
  customerId: uuid.optional(),
  collectedBy: uuid.optional(),
  status: z.enum(PAYMENT_STATUSES).optional(),
  mode: z.enum([...PAYMENT_MODES, 'LEGACY_UNKNOWN']).optional(),
  from: businessDate.optional(),
  to: businessDate.optional(),
});
export type ListPaymentsQuery = z.infer<typeof listPaymentsQuery>;

// ---------------------------------------------------------------------------
// Credits, debits, refunds, opening balance
// ---------------------------------------------------------------------------

export const creditRequest = z.object({
  kind: z.enum(['DISCOUNT', 'CREDIT_ADJUSTMENT']),
  amount: positiveMoney,
  targetInvoiceId: uuid.nullish(),
  reason,
});
export type CreditRequest = z.infer<typeof creditRequest>;

export const debitRequest = z.object({
  amount: positiveMoney,
  description: trimmed(300),
  dueDate: businessDate.optional(),
  reason,
});
export type DebitRequest = z.infer<typeof debitRequest>;

export const refundRequest = z.object({
  amount: positiveMoney,
  mode: z.enum(PAYMENT_MODES),
  reference: z.string().trim().max(100).nullish(),
  reason,
});
export type RefundRequest = z.infer<typeof refundRequest>;

export const openingBalanceRequest = z.object({
  /** Positive = customer owes (due); negative = advance held. */
  amount: signedMoney,
  asOf: businessDate,
  reason,
});
export type OpeningBalanceRequest = z.infer<typeof openingBalanceRequest>;

export const reverseCreditRequest = z.object({ reason });

