export const submitHandoverRequest = z.object({ declaredAmount: nonNegativeMoney, notes: optionalTrimmed(500) });
export type SubmitHandoverRequest = z.infer<typeof submitHandoverRequest>;

export const confirmHandoverRequest = z.object({
  receivedAmount: nonNegativeMoney,
  mismatchReason: optionalTrimmed(500),
});
export type ConfirmHandoverRequest = z.infer<typeof confirmHandoverRequest>;

export const cashAdjustmentRequest = z.object({
  agentId: uuid,
  /** Positive reduces what the agent owes (recovery/write-off); negative increases it. */
  amount: signedMoney,
  kind: z.enum(['RECOVERY', 'WRITE_OFF', 'CORRECTION']),
  handoverId: uuid.nullish(),
  reason,
});
export type CashAdjustmentRequest = z.infer<typeof cashAdjustmentRequest>;
